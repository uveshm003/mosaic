export const ERODE_TRACKING_EM = -0.04

/** Width of a word in em at the monument's tracking; unknown characters count as an average letter. */
export function wordWidthEm(word: string): number {
  return Array.from(word).reduce(
    (sum, ch) => sum + (erode500Advances[ch] ?? 0.5) + ERODE_TRACKING_EM,
    0,
  )
}
